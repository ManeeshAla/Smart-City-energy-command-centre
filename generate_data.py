#!/usr/bin/env python3
"""
Build the hourly city energy dataset used by the pipeline.

Input : smart_city_dataset.csv            (5,000 cities, static attributes)
Output: smart_city_energy_timeseries.csv  (40 cities x 90 days x 24 hours)

The static attributes of each selected city (population, area, smart grid
adoption, ...) are kept from the supplied file.  The hourly columns
(temperature, energy, lags) are generated by a seeded simulation, so every run
produces identical data.

Energy model (MWh per hour)
    energy = base_load x smart_grid_saving x daily_profile x weekday_factor
             x temperature_factor x (1 + AR(1) noise) x grid_stress_event

Run:  python generate_data.py
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "smart_city_dataset.csv"
OUT = ROOT / "smart_city_energy_timeseries.csv"

SEED = 42
N_CITIES = 40
MIN_POPULATION = 500_000
DAYS = 90
TRAIN_DAYS = 70                 # first 70 days train, last 20 days test
START = "2025-06-01 00:00"
SPIKE_QUANTILE = 0.90           # spike = above the city's own 90th percentile (train period)

HEAT_WAVE_DAYS = [(22, 25), (47, 51), (76, 79), (84, 86)]   # (start_day, end_day)

STATIC_COLS = [
    "Population", "Area (sq. km)", "Smart Infrastructure Score",
    "Public Transport Usage", "Smart Grid Adoption", "Internet Speed (Mbps)",
]


def daily_profile(hour: np.ndarray) -> np.ndarray:
    """Morning and evening demand peaks."""
    return (0.68
            + 0.20 * np.exp(-((hour - 8) / 2.6) ** 2)
            + 0.34 * np.exp(-((hour - 19) / 3.0) ** 2))


def ar1(rng: np.random.Generator, n: int, phi: float, sigma: float) -> np.ndarray:
    eps = rng.normal(0, sigma, n)
    out = np.empty(n)
    out[0] = eps[0]
    for i in range(1, n):
        out[i] = phi * out[i - 1] + eps[i]
    return out


def pick_cities(df: pd.DataFrame) -> pd.DataFrame:
    """Evenly spaced rows after sorting by population (mid-size to large cities, 500k+)."""
    ordered = df[df["Population"] >= MIN_POPULATION].sort_values("Population").reset_index(drop=True)
    idx = np.linspace(0, len(ordered) - 1, N_CITIES).round().astype(int)
    return ordered.iloc[idx].reset_index(drop=True)


def main() -> None:
    rng = np.random.default_rng(SEED)
    cities = pick_cities(pd.read_csv(SRC))
    hours = DAYS * 24
    ts = pd.date_range(START, periods=hours, freq="h")
    hour = ts.hour.to_numpy()
    dow = ts.dayofweek.to_numpy()
    day = np.arange(hours) // 24

    # Shared weather: one slow seasonal hump plus heat waves that hit every city.
    seasonal = 4.0 * np.sin(np.pi * np.arange(hours) / hours)
    heat = np.zeros(hours)
    for a, b in HEAT_WAVE_DAYS:
        mask = (day >= a) & (day <= b)
        ramp = np.sin(np.pi * (day[mask] - a + 0.5) / (b - a + 1))
        heat[mask] = 9.0 * ramp
    weekday_factor = np.where(dow == 5, 0.90, np.where(dow == 6, 0.85, 1.0))
    daily = daily_profile(hour)

    frames = []
    for _, c in cities.iterrows():
        pop, area = c["Population"], c["Area (sq. km)"]
        base_load = 2 + 27 * (pop / 1e6) + 3 * (area / 1000)      # MWh/h, scales with city size
        saving = 1 - 0.18 * c["Smart Grid Adoption"] / 100
        climate = rng.uniform(14, 24)                      # city's average temperature
        temp = (climate + seasonal + heat * rng.uniform(0.8, 1.2)
                + 5.5 * np.sin(2 * np.pi * (hour - 9) / 24)
                + ar1(rng, hours, 0.9, 0.6))
        temp_factor = (1 + 0.032 * np.clip(temp - 22, 0, None)
                       + 0.010 * np.clip(10 - temp, 0, None))
        noise = 1 + ar1(rng, hours, 0.6, 0.018)
        stress = np.where(rng.random(hours) < 0.004, rng.uniform(1.25, 1.55, hours), 1.0)
        energy = base_load * saving * daily * weekday_factor * temp_factor * noise * stress

        f = pd.DataFrame({
            "timestamp": ts,
            "city": c["City Name"],
            **{col: c[col] for col in STATIC_COLS},
            "hour": hour,
            "dayofweek": dow,
            "is_weekend": (dow >= 5).astype(int),
            "temperature_c": temp.round(2),
            "energy_mwh": energy.round(2),
        })
        e = f["energy_mwh"]
        f["lag_1h"] = e.shift(1)
        f["lag_24h"] = e.shift(24)
        f["rolling_24h_mean"] = e.shift(1).rolling(24).mean().round(2)
        f["day_index"] = day
        train_cut = f["day_index"] < TRAIN_DAYS
        f["spike_threshold"] = e[train_cut].quantile(SPIKE_QUANTILE).round(2)
        f["is_spike"] = (e > f["spike_threshold"]).astype(int)
        frames.append(f.iloc[24:])                          # drop rows without 24 h of history

    out = pd.concat(frames, ignore_index=True)
    out = out.sort_values(["timestamp", "city"]).reset_index(drop=True)
    out.to_csv(OUT, index=False)

    train = out[out["day_index"] < TRAIN_DAYS]
    test = out[out["day_index"] >= TRAIN_DAYS]
    print(f"Wrote {OUT.name}: {len(out):,} rows, {out['city'].nunique()} cities")
    print(f"  period   : {out['timestamp'].min()}  ->  {out['timestamp'].max()}")
    print(f"  energy   : mean {out['energy_mwh'].mean():.1f}  max {out['energy_mwh'].max():.1f} MWh")
    print(f"  split    : train {len(train):,} rows | test {len(test):,} rows")
    print(f"  spike %  : train {train['is_spike'].mean():.1%} | test {test['is_spike'].mean():.1%}")


if __name__ == "__main__":
    main()
